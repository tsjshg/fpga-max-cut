#!/usr/bin/env python3
"""G-set の形（1 行目「頂点数 辺数」、以下「i j w」・頂点は 1 から）を、この回路の .adj に直す。

確かめること（どれかが外れたら止まる）:
  - 重みがすべて 1（重みなしの Max-Cut だけを扱う）
  - 自己ループ・多重辺が無い
  - 全頂点の次数が同じ（回路は次数固定）
あわせて、二部グラフかどうかを出す。二部グラフなら全部の辺を切れるので、最大カット = 辺数（最適値が分かる）。

使い方: python3 -I sw/gset2adj.py data/gset/G48 -o data/gset/G48.adj
（ダウンロードしたファイルはデータとしてだけ読む。-I で、そのフォルダの .py を読み込まない）
"""
import argparse
import sys
from collections import deque


def read_gset(path):
    with open(path) as f:
        n, m = map(int, f.readline().split())
        edges = []
        for line in f:
            if not line.strip():
                continue
            i, j, w = line.split()
            edges.append((int(i) - 1, int(j) - 1, int(w)))
    if len(edges) != m:
        sys.exit(f"{path}: 辺の数が見出し（{m}）と違う（{len(edges)}）")
    return n, edges


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("gset")
    ap.add_argument("-o", "--out", required=True)
    a = ap.parse_args()
    n, edges = read_gset(a.gset)
    adj = [[] for _ in range(n)]
    seen = set()
    for u, v, w in edges:
        if w != 1:
            sys.exit(f"重みが 1 でない辺がある: {u + 1} {v + 1} {w}")
        if u == v or not (0 <= u < n and 0 <= v < n):
            sys.exit(f"自己ループか範囲外: {u + 1} {v + 1}")
        key = (min(u, v), max(u, v))
        if key in seen:
            sys.exit(f"多重辺: {u + 1} {v + 1}")
        seen.add(key)
        adj[u].append(v)
        adj[v].append(u)
    degs = {len(nb) for nb in adj}
    if len(degs) != 1:
        sys.exit(f"次数がそろっていない: {sorted(degs)}")
    d = degs.pop()

    # 二部グラフかどうか（幅優先で 2 色に塗れるか）
    color = [-1] * n
    bipartite = True
    for s in range(n):
        if color[s] >= 0:
            continue
        color[s] = 0
        q = deque([s])
        while q:
            x = q.popleft()
            for y in adj[x]:
                if color[y] < 0:
                    color[y] = color[x] ^ 1
                    q.append(y)
                elif color[y] == color[x]:
                    bipartite = False
    name = a.gset.rsplit("/", 1)[-1]
    note = "bipartite: max cut = |E| (optimal)" if bipartite else "not bipartite"
    with open(a.out, "w") as f:
        f.write(f"# {name} from G-set (Helmberg-Rendl, generated by rudy), converted by gset2adj.py; {note}\n")
        f.write(f"{n} {d}\n")
        for nb in adj:
            f.write(" ".join(map(str, sorted(nb))) + "\n")
    print(f"{name}: n={n} d={d} edges={len(edges)} {note}")


if __name__ == "__main__":
    main()
